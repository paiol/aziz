using Microsoft.EntityFrameworkCore;
using ComparacaoPropostas.Models.Entities;
using ComparacaoPropostas.Models.Entities.Enums;

namespace ComparacaoPropostas.Data;

public class AppDbContext : DbContext
{
    public AppDbContext(DbContextOptions<AppDbContext> options) : base(options) { }

    public DbSet<Processo> Processos => Set<Processo>();
    public DbSet<Criterio> Criterios => Set<Criterio>();
    public DbSet<Proposta> Propostas => Set<Proposta>();
    public DbSet<Avaliador> Avaliadores => Set<Avaliador>();
    public DbSet<Fornecedor> Fornecedores => Set<Fornecedor>();
    public DbSet<MemoriaCalculoAvaliacao> MemoriaCalculoAvaliacao => Set<MemoriaCalculoAvaliacao>();
    public DbSet<Avaliacao> Avaliacoes => Set<Avaliacao>();
    public DbSet<ItemMaterial> ItensMaterial => Set<ItemMaterial>();
    public DbSet<ItemProposta> ItensProposta => Set<ItemProposta>();
    public DbSet<PropostaAnexo> PropostasAnexo => Set<PropostaAnexo>();
    public DbSet<PedidoProposta> Pedidos => Set<PedidoProposta>();
    public DbSet<ItemPedido> ItensPedido => Set<ItemPedido>();

    // Base de Dados — catálogos independentes por área, ainda sem ligação a
    // Propostas/Pedidos (fica para uma alteração futura).
    public DbSet<ItemEnergia> ItensEnergia => Set<ItemEnergia>();
    public DbSet<ItemMbb> ItensMbb => Set<ItemMbb>();
    public DbSet<ItemFbb> ItensFbb => Set<ItemFbb>();
    public DbSet<ItemCore> ItensCore => Set<ItemCore>();
    public DbSet<ItemCcv> ItensCcv => Set<ItemCcv>();

    // Módulo Obras — registo de projetos de construção civil, mapa de quantidades e
    // comparação de propostas de empreiteiros. Domínio totalmente independente do resto
    // do modelo (sem FKs para Processo/Proposta/ItemMaterial/Criterio/Avaliacao).
    public DbSet<ProjetoObra> ProjetosObra => Set<ProjetoObra>();
    public DbSet<ProjetoObraAnexo> ProjetoObraAnexos => Set<ProjetoObraAnexo>();
    public DbSet<ItemMQT> ItensMQT => Set<ItemMQT>();
    public DbSet<CriterioObra> CriteriosObra => Set<CriterioObra>();
    public DbSet<PropostaEmpreiteiro> PropostasEmpreiteiro => Set<PropostaEmpreiteiro>();
    public DbSet<ItemPropostaEmpreiteiro> ItensPropostaEmpreiteiro => Set<ItemPropostaEmpreiteiro>();
    public DbSet<AvaliacaoObra> AvaliacoesObra => Set<AvaliacaoObra>();

    // Módulo Plano — plano anual do departamento (ficheiro SCOPE_INF): projetos do plano
    // e ações de formação/feiras. Independente do resto do modelo.
    public DbSet<Plano> Planos => Set<Plano>();
    public DbSet<ProjetoPlano> ProjetosPlano => Set<ProjetoPlano>();
    public DbSet<AcaoFormacaoPlano> AcoesFormacaoPlano => Set<AcaoFormacaoPlano>();
    public DbSet<ValorLista> ValoresLista => Set<ValorLista>();

    // Gestão de Stock — materiais em armazém por área, entradas (Packing List Huawei, compras), saídas e nºs de série.
    public DbSet<MaterialStock> MateriaisStock => Set<MaterialStock>();
    public DbSet<EntradaStock> EntradasStock => Set<EntradaStock>();
    public DbSet<MovimentoStock> MovimentosStock => Set<MovimentoStock>();
    public DbSet<NumeroSerieStock> NumerosSerieStock => Set<NumeroSerieStock>();
    public DbSet<InventarioStock> InventariosStock => Set<InventarioStock>();
    public DbSet<LinhaInventario> LinhasInventario => Set<LinhaInventario>();
    public DbSet<DivergenciaNomeMaterial> DivergenciasNomeMaterial => Set<DivergenciaNomeMaterial>();
    public DbSet<ArmazemStock> ArmazensStock => Set<ArmazemStock>();
    public DbSet<CodigoFornecedorMaterial> CodigosFornecedorMaterial => Set<CodigoFornecedorMaterial>();

    // Integração App → Airtable (ver Services/Airtable).
    public DbSet<AirtableLink> AirtableLinks => Set<AirtableLink>();
    public DbSet<AirtableSyncPendente> AirtableSyncPendentes => Set<AirtableSyncPendente>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Processo>(e =>
        {
            e.Property(p => p.NumeroProcesso).HasMaxLength(30).HasDefaultValue("");
            e.Property(p => p.Status).HasConversion<string>().HasMaxLength(20);
            e.Property(p => p.TipoCompra).HasConversion<string>().HasMaxLength(20).HasDefaultValue(TipoCompra.Nacional);
            e.Property(p => p.TaxaCambioPadrao).HasPrecision(18, 4);
            e.Property(p => p.ValorAdjudicado).HasPrecision(18, 2);
            e.Property(p => p.ValorAdjudicadoMoeda).HasMaxLength(10);
            e.Property(p => p.ValorAdjudicadoCVE).HasPrecision(18, 2);
            e.Property(p => p.PontuacaoAdjudicada).HasPrecision(5, 2);

            // 1-1: a Processo is always generated by exactly one PedidoProposta.
            e.HasOne(p => p.PedidoProposta)
                .WithOne(pp => pp.Processo)
                .HasForeignKey<Processo>(p => p.PedidoPropostaId)
                .OnDelete(DeleteBehavior.Restrict);

            // 1-1 opcional com a proposta adjudicada
            e.HasOne(p => p.PropostaVencedora)
                .WithMany()
                .HasForeignKey(p => p.PropostaVencedoraId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<Proposta>(e =>
        {
            e.Property(p => p.Status).HasConversion<string>().HasMaxLength(20);
            e.Property(p => p.Moeda).HasMaxLength(10);
            e.Property(p => p.TaxaCambio).HasPrecision(18, 4);
            e.Property(p => p.ValorTotal).HasPrecision(18, 2);
            e.Property(p => p.Garantia).HasMaxLength(200);

            e.HasOne(p => p.Processo)
                .WithMany(pr => pr.Propostas)
                .HasForeignKey(p => p.ProcessoId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<PedidoProposta>(e =>
        {
            e.Property(p => p.Status).HasConversion<string>().HasMaxLength(20);
            e.Property(p => p.Area).HasConversion<string>().HasMaxLength(20);
            e.Property(p => p.OrcamentoEstimado).HasPrecision(18, 2);

            // Restrict: um projeto Capex com compras associadas não pode ser apagado.
            e.HasOne(p => p.ProjetoPlano)
                .WithMany(pp => pp.Pedidos)
                .HasForeignKey(p => p.ProjetoPlanoId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<ItemPedido>(e =>
        {
            e.Property(p => p.QuantidadeSolicitada).HasPrecision(18, 3);

            e.HasOne(ip => ip.PedidoProposta)
                .WithMany(pp => pp.ItensPedido)
                .HasForeignKey(ip => ip.PedidoPropostaId)
                .OnDelete(DeleteBehavior.Cascade);

            e.HasOne(ip => ip.ItemMaterial)
                .WithMany()
                .HasForeignKey(ip => ip.ItemMaterialId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<Criterio>(e =>
        {
            e.Property(c => c.Peso).HasPrecision(5, 2);
            e.Property(c => c.TipoAutomatico).HasConversion<string>().HasMaxLength(20).HasDefaultValue(TipoCriterioAutomatico.Nenhum);

            e.HasOne(c => c.Processo)
                .WithMany(p => p.Criterios)
                .HasForeignKey(c => c.ProcessoId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<MemoriaCalculoAvaliacao>(e =>
        {
            e.Property(m => m.Nota).HasPrecision(5, 2);
            e.Property(m => m.Justificativa).HasMaxLength(500);

            e.HasOne(m => m.Proposta)
                .WithMany(p => p.MemoriaCalculo)
                .HasForeignKey(m => m.PropostaId)
                .OnDelete(DeleteBehavior.Cascade);

            e.HasOne(m => m.Criterio)
                .WithMany()
                .HasForeignKey(m => m.CriterioId)
                .OnDelete(DeleteBehavior.Restrict);

            e.HasIndex(m => new { m.PropostaId, m.CriterioId }).IsUnique();
        });

        modelBuilder.Entity<Avaliador>(e =>
        {
            e.Property(a => a.Nome).HasMaxLength(200);
            e.Property(a => a.Perfil).HasMaxLength(100);
            e.Property(a => a.Email).HasMaxLength(200);
        });

        modelBuilder.Entity<Fornecedor>(e =>
        {
            e.Property(f => f.Nome).HasMaxLength(200);
            e.Property(f => f.Tipo).HasMaxLength(50);
            e.Property(f => f.Contribuinte).HasMaxLength(50);
            e.Property(f => f.Contacto).HasMaxLength(50);
            e.Property(f => f.Email).HasMaxLength(200);
            e.HasIndex(f => f.Nome).IsUnique();
        });

        modelBuilder.Entity<Avaliacao>(e =>
        {
            e.HasOne(a => a.Proposta)
                .WithMany(p => p.Avaliacoes)
                .HasForeignKey(a => a.PropostaId)
                .OnDelete(DeleteBehavior.Cascade);

            e.HasOne(a => a.Criterio)
                .WithMany(c => c.Avaliacoes)
                .HasForeignKey(a => a.CriterioId)
                .OnDelete(DeleteBehavior.Restrict);

            e.HasOne(a => a.Avaliador)
                .WithMany(av => av.Avaliacoes)
                .HasForeignKey(a => a.AvaliadorId)
                .OnDelete(DeleteBehavior.Restrict);

            e.HasIndex(a => new { a.PropostaId, a.CriterioId, a.AvaliadorId }).IsUnique();
        });

        modelBuilder.Entity<ItemMaterial>(e =>
        {
            e.HasOne(im => im.ItemPai)
                .WithMany(im => im.SubItens)
                .HasForeignKey(im => im.ItemPaiId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<ItemProposta>(e =>
        {
            e.Property(p => p.Quantidade).HasPrecision(18, 3);
            e.Property(p => p.QuantidadeSolicitada).HasPrecision(18, 3);
            e.Property(p => p.PrecoUnitario).HasPrecision(18, 2);

            e.HasOne(ip => ip.Proposta)
                .WithMany(p => p.ItensProposta)
                .HasForeignKey(ip => ip.PropostaId)
                .OnDelete(DeleteBehavior.Cascade);

            e.HasOne(ip => ip.ItemMaterial)
                .WithMany(im => im.ItensProposta)
                .HasForeignKey(ip => ip.ItemMaterialId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<PropostaAnexo>(e =>
        {
            e.HasOne(a => a.Proposta)
                .WithMany(p => p.Anexos)
                .HasForeignKey(a => a.PropostaId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        // Módulo Obras — todas as relações contidas dentro deste próprio grupo de tabelas.
        modelBuilder.Entity<ProjetoObra>(e =>
        {
            e.Property(p => p.Tipo).HasConversion<string>().HasMaxLength(20);
            e.Property(p => p.Status).HasConversion<string>().HasMaxLength(20);
            e.Property(p => p.ValorEstimado).HasPrecision(18, 2);
            e.Property(p => p.ValorAdjudicado).HasPrecision(18, 2);

            e.HasOne(p => p.PropostaVencedora)
                .WithMany()
                .HasForeignKey(p => p.PropostaVencedoraId)
                .OnDelete(DeleteBehavior.Restrict);

            // Restrict: um projeto Capex com obras associadas não pode ser apagado.
            e.HasOne(p => p.ProjetoPlano)
                .WithMany(pp => pp.Obras)
                .HasForeignKey(p => p.ProjetoPlanoId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<ProjetoObraAnexo>(e =>
        {
            e.Property(a => a.TipoDocumento).HasConversion<string>().HasMaxLength(30);

            e.HasOne(a => a.ProjetoObra)
                .WithMany(p => p.Anexos)
                .HasForeignKey(a => a.ProjetoObraId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<ItemMQT>(e =>
        {
            e.Property(i => i.Quantidade).HasPrecision(18, 3);

            e.HasOne(i => i.ProjetoObra)
                .WithMany(p => p.ItensMQT)
                .HasForeignKey(i => i.ProjetoObraId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<CriterioObra>(e =>
        {
            e.Property(c => c.Peso).HasPrecision(5, 2);

            e.HasOne(c => c.ProjetoObra)
                .WithMany(p => p.Criterios)
                .HasForeignKey(c => c.ProjetoObraId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<PropostaEmpreiteiro>(e =>
        {
            e.Property(p => p.Status).HasConversion<string>().HasMaxLength(20);

            e.HasOne(p => p.ProjetoObra)
                .WithMany(o => o.Propostas)
                .HasForeignKey(p => p.ProjetoObraId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<ItemPropostaEmpreiteiro>(e =>
        {
            e.Property(i => i.QuantidadeFornecida).HasPrecision(18, 3);
            e.Property(i => i.PrecoUnitario).HasPrecision(18, 2);

            e.HasOne(i => i.PropostaEmpreiteiro)
                .WithMany(p => p.ItensProposta)
                .HasForeignKey(i => i.PropostaEmpreiteiroId)
                .OnDelete(DeleteBehavior.Cascade);

            e.HasOne(i => i.ItemMQT)
                .WithMany(m => m.ItensProposta)
                .HasForeignKey(i => i.ItemMQTId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<AvaliacaoObra>(e =>
        {
            e.HasOne(a => a.PropostaEmpreiteiro)
                .WithMany(p => p.Avaliacoes)
                .HasForeignKey(a => a.PropostaEmpreiteiroId)
                .OnDelete(DeleteBehavior.Cascade);

            e.HasOne(a => a.CriterioObra)
                .WithMany(c => c.Avaliacoes)
                .HasForeignKey(a => a.CriterioObraId)
                .OnDelete(DeleteBehavior.Restrict);

            e.HasIndex(a => new { a.PropostaEmpreiteiroId, a.CriterioObraId }).IsUnique();
        });

        // Gestão de Stock
        modelBuilder.Entity<MaterialStock>(e =>
        {
            e.HasIndex(m => m.Codigo).IsUnique();
            e.Property(m => m.StockMinimo).HasPrecision(18, 3);
            e.Property(m => m.PrecoUnitario).HasPrecision(18, 2);
        });

        modelBuilder.Entity<EntradaStock>(e =>
        {
            e.Property(x => x.Tipo).HasConversion<string>().HasMaxLength(30);
            e.Property(x => x.Area).HasConversion<string>().HasMaxLength(20);
            e.HasIndex(x => x.Contrato1Mais1);
            e.HasOne(x => x.ProjetoPlano).WithMany().HasForeignKey(x => x.ProjetoPlanoId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne(x => x.PedidoProposta).WithMany().HasForeignKey(x => x.PedidoPropostaId).OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<MovimentoStock>(e =>
        {
            e.Property(x => x.Tipo).HasConversion<string>().HasMaxLength(20);
            e.Property(x => x.Area).HasConversion<string>().HasMaxLength(20);
            e.Property(x => x.Quantidade).HasPrecision(18, 3);
            e.HasIndex(x => new { x.MaterialStockId, x.Area });
            e.HasOne(x => x.Material).WithMany(m => m.Movimentos).HasForeignKey(x => x.MaterialStockId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne(x => x.Entrada).WithMany(en => en.Movimentos).HasForeignKey(x => x.EntradaStockId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne(x => x.ProjetoPlano).WithMany().HasForeignKey(x => x.ProjetoPlanoId).OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<NumeroSerieStock>(e =>
        {
            e.Property(x => x.Area).HasConversion<string>().HasMaxLength(20);
            e.Property(x => x.Estado).HasConversion<string>().HasMaxLength(20);
            e.HasIndex(x => new { x.MaterialStockId, x.Serie }).IsUnique();
            e.HasOne(x => x.Material).WithMany(m => m.NumerosSerie).HasForeignKey(x => x.MaterialStockId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne(x => x.Entrada).WithMany().HasForeignKey(x => x.EntradaStockId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne(x => x.MovimentoSaida).WithMany().HasForeignKey(x => x.MovimentoSaidaId).OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<InventarioStock>(e =>
        {
            e.Property(x => x.Area).HasConversion<string>().HasMaxLength(20);
            e.Property(x => x.Estado).HasConversion<string>().HasMaxLength(20);
        });

        modelBuilder.Entity<LinhaInventario>(e =>
        {
            e.Property(x => x.QuantidadeContada).HasPrecision(18, 3);
            e.Property(x => x.QuantidadeSistema).HasPrecision(18, 3);
            e.HasOne(x => x.Inventario).WithMany(i => i.Linhas).HasForeignKey(x => x.InventarioStockId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne(x => x.Material).WithMany().HasForeignKey(x => x.MaterialStockId).OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<MovimentoStock>()
            .HasOne(x => x.Inventario).WithMany().HasForeignKey(x => x.InventarioStockId).OnDelete(DeleteBehavior.Restrict);

        modelBuilder.Entity<CodigoFornecedorMaterial>(e =>
        {
            e.HasIndex(x => new { x.Fornecedor, x.Codigo }).IsUnique();
            e.HasIndex(x => x.Codigo);
            e.HasOne(x => x.Material).WithMany(m => m.CodigosFornecedor).HasForeignKey(x => x.MaterialStockId).OnDelete(DeleteBehavior.Cascade);
        });
        modelBuilder.Entity<ArmazemStock>(e =>
        {
            e.HasIndex(x => x.Codigo).IsUnique();
            e.Ignore(x => x.Rotulo);
        });
        modelBuilder.Entity<MovimentoStock>().HasIndex(x => new { x.MaterialStockId, x.Area, x.Armazem });

        modelBuilder.Entity<DivergenciaNomeMaterial>(e =>
        {
            e.Property(x => x.Origem).HasConversion<string>().HasMaxLength(20);
            e.Property(x => x.Estado).HasConversion<string>().HasMaxLength(20);
            e.HasIndex(x => new { x.MaterialStockId, x.Estado });
            e.HasOne(x => x.Material).WithMany(m => m.DivergenciasNome).HasForeignKey(x => x.MaterialStockId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne(x => x.Entrada).WithMany().HasForeignKey(x => x.EntradaStockId).OnDelete(DeleteBehavior.SetNull);
            e.HasOne(x => x.Inventario).WithMany().HasForeignKey(x => x.InventarioStockId).OnDelete(DeleteBehavior.SetNull);
        });

        // Módulo Plano — listas de escolha (valores iniciais da folha "Listas" do ficheiro SCOPE)
        modelBuilder.Entity<ValorLista>(e =>
        {
            e.Property(v => v.Lista).HasConversion<string>().HasMaxLength(30);
            e.Property(v => v.Valor).HasMaxLength(200);
            e.HasIndex(v => new { v.Lista, v.Valor }).IsUnique();
            e.HasData(ComparacaoPropostas.Services.ListasPlano.Semente());
        });

        // Módulo Plano
        modelBuilder.Entity<Plano>(e =>
        {
            e.Property(p => p.CapacidadeArquiteturaDias).HasPrecision(9, 2);
            e.Property(p => p.CapacidadeEnergiaDias).HasPrecision(9, 2);
        });

        modelBuilder.Entity<ProjetoPlano>(e =>
        {
            e.Property(p => p.Situacao).HasConversion<string>().HasMaxLength(30);
            e.Property(p => p.Prioridade).HasConversion<string>().HasMaxLength(10);
            e.Property(p => p.ExecucaoAnoAnterior).HasPrecision(9, 4);
            e.Property(p => p.EsforcoArquiteturaDias).HasPrecision(9, 2);
            e.Property(p => p.EsforcoEnergiaDias).HasPrecision(9, 2);
            foreach (var valor in new[] { nameof(ProjetoPlano.PropostasSemAdjudicacao), nameof(ProjetoPlano.AdjudicadoAnoAnterior),
                         nameof(ProjetoPlano.AdjudicadoAnosAnteriores), nameof(ProjetoPlano.ValorTransitar), nameof(ProjetoPlano.ValorNovo),
                         nameof(ProjetoPlano.ValorCondicionado), nameof(ProjetoPlano.TotalOrcamentoAnoAnterior), nameof(ProjetoPlano.CustoAquisicaoSite),
                         nameof(ProjetoPlano.CustoEquipamento), nameof(ProjetoPlano.CustoConstrucoes), nameof(ProjetoPlano.CustoServicos),
                         nameof(ProjetoPlano.CustoDeslocacoes), nameof(ProjetoPlano.CustoTerceirizacao) })
            {
                e.Property<decimal?>(valor).HasPrecision(18, 2);
            }

            e.Property(p => p.Area).HasConversion<string>().HasMaxLength(20);
            e.Property(p => p.EstadoAprovacao).HasConversion<string>().HasMaxLength(20);
            e.HasIndex(p => new { p.PlanoId, p.Area });

            e.HasOne(p => p.ProjetoOrigem)
                .WithMany()
                .HasForeignKey(p => p.ProjetoOrigemId)
                .OnDelete(DeleteBehavior.ClientSetNull);

            e.HasOne(p => p.Plano)
                .WithMany(pl => pl.Projetos)
                .HasForeignKey(p => p.PlanoId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<AcaoFormacaoPlano>(e =>
        {
            e.Property(a => a.Tipo).HasConversion<string>().HasMaxLength(20);
            e.Property(a => a.Dias).HasPrecision(9, 2);
            e.Property(a => a.InscricaoPorPessoa).HasPrecision(18, 2);
            e.Property(a => a.PassagemPorPessoa).HasPrecision(18, 2);
            e.Property(a => a.EstadiaDia).HasPrecision(18, 2);
            e.Property(a => a.AjudaCustoDia).HasPrecision(18, 2);

            e.HasOne(a => a.Plano)
                .WithMany(pl => pl.AcoesFormacao)
                .HasForeignKey(a => a.PlanoId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        // Integração App → Airtable
        modelBuilder.Entity<AirtableLink>(e =>
        {
            e.Property(l => l.TabelaId).HasMaxLength(20);
            e.Property(l => l.Chave).HasMaxLength(50);
            e.Property(l => l.RecordId).HasMaxLength(20);
            e.HasIndex(l => new { l.TabelaId, l.Chave }).IsUnique();
            e.HasIndex(l => l.ProcessoId);
        });

        modelBuilder.Entity<AirtableSyncPendente>(e =>
        {
            e.Property(p => p.Tipo).HasMaxLength(20);
            e.Property(p => p.Erro).HasMaxLength(1000);
            e.HasIndex(p => new { p.ProcessadoEm, p.ProximaTentativaEm });
        });
    }
}
